"""Durable queue and checkpoint-scoped foundation assessments, separate from trading."""
from __future__ import annotations

import json
import os
import sqlite3
import time
from pathlib import Path

from .curriculum import IDS, MANIFEST_HASH, SUITE_HASH, SUITES, digest
from .rights import license_blockers

ROOT = Path(__file__).resolve().parents[2]

def brain_key(profile: dict) -> str:
    return digest({"endpoint": profile["endpoint"].rstrip("/"), "chat_path": profile.get("chat_path", "/brain/chat"), "id": profile.get("id", "configured")})

class LearningStore:
    def __init__(self, path: Path | str | None = None):
        self.path = Path(path or os.getenv("WIZARD_LEARNING_DB", str(ROOT / "data" / "wizard_learning.sqlite3")))
        self.path.parent.mkdir(parents=True, exist_ok=True)
        with self.connect() as db:
            db.executescript("""
                CREATE TABLE IF NOT EXISTS queue (id TEXT PRIMARY KEY, created REAL NOT NULL, kind TEXT NOT NULL,
                    payload TEXT NOT NULL, state TEXT NOT NULL DEFAULT 'queued', error TEXT NOT NULL DEFAULT '');
                CREATE TABLE IF NOT EXISTS assessments (brain TEXT PRIMARY KEY, revision INTEGER NOT NULL,
                    checkpoint TEXT NOT NULL, created REAL NOT NULL, manifest TEXT NOT NULL, suite TEXT NOT NULL, report TEXT NOT NULL);
                CREATE TABLE IF NOT EXISTS revisions (brain TEXT PRIMARY KEY, revision INTEGER NOT NULL DEFAULT 0);
                CREATE TABLE IF NOT EXISTS events (seq INTEGER PRIMARY KEY AUTOINCREMENT, created REAL NOT NULL, brain TEXT NOT NULL, kind TEXT NOT NULL, payload TEXT NOT NULL);
            """)

    def connect(self):
        db = sqlite3.connect(self.path, timeout=10)
        db.row_factory = sqlite3.Row
        return db

    def revision(self, key: str) -> int:
        with self.connect() as db:
            row = db.execute("SELECT revision FROM revisions WHERE brain=?", (key,)).fetchone()
        return row[0] if row else 0

    def invalidate(self, key: str, reason: str) -> None:
        with self.connect() as db:
            db.execute("INSERT INTO revisions VALUES (?,1) ON CONFLICT(brain) DO UPDATE SET revision=revision+1", (key,))
            db.execute("INSERT INTO events(created,brain,kind,payload) VALUES (?,?,?,?)", (time.time(), key, "learning-boundary", json.dumps({"reason": reason})))

    def record_assessment(self, key: str, checkpoint: str, revision: int, report: dict) -> None:
        if not checkpoint: raise ValueError("Assessment requires an immutable checkpoint identifier.")
        # Outcomes are generated by the evaluator, never by a frontend 'passed' toggle.
        with self.connect() as db:
            db.execute("INSERT OR REPLACE INTO assessments VALUES (?,?,?,?,?,?,?)", (key, revision, checkpoint, time.time(), MANIFEST_HASH, SUITE_HASH, json.dumps(report)))

    def admit_expansion(self, key: str, checkpoint: str, reason: str, queue_id: str | None = None) -> None:
        """Serialize admission and consume the assessment before any remote write."""
        with self.connect() as db:
            db.execute("BEGIN IMMEDIATE")
            gate = self.gate(key, checkpoint)
            if not gate["ready"]: raise PermissionError("Foundation gate is closed: " + "; ".join(gate["blockers"]))
            if queue_id is not None:
                changed = db.execute("UPDATE queue SET state='processing' WHERE id=? AND state='queued'", (queue_id,)).rowcount
                if changed != 1: raise ValueError("Queue item is not available for processing")
            db.execute("INSERT INTO revisions VALUES (?,1) ON CONFLICT(brain) DO UPDATE SET revision=revision+1", (key,))
            db.execute("INSERT INTO events(created,brain,kind,payload) VALUES (?,?,?,?)", (time.time(), key, "learning-admitted", json.dumps({"reason": reason, "queue_id": queue_id})))

    def gate(self, key: str, checkpoint: str = "") -> dict:
        reasons = []
        with self.connect() as db:
            row = db.execute("SELECT * FROM assessments WHERE brain=?", (key,)).fetchone()
        if not checkpoint: reasons.append("Configure the deployed model's immutable checkpoint ID before admission.")
        report = json.loads(row["report"]) if row else {}
        if not row: reasons.append("Foundation grounding, transfer, joint-prerogative, and retention assessments have not passed.")
        else:
            if row["checkpoint"] != checkpoint: reasons.append("Assessment belongs to a different checkpoint.")
            if row["revision"] != self.revision(key): reasons.append("Learning changed the model; recheck foundational retention.")
            if row["manifest"] != MANIFEST_HASH or row["suite"] != SUITE_HASH: reasons.append("Curriculum or prerogatives changed; reassessment is required.")
            if time.time() - row["created"] > 86400: reasons.append("Foundation evidence is older than 24 hours.")
            for name, cases in SUITES.items():
                outcomes = report.get(name)
                if not isinstance(outcomes, list) or len(outcomes) != len(cases) or {item.get("case_id") for item in outcomes if isinstance(item, dict)} != {case["id"] for case in cases} or not all(isinstance(item, dict) and item.get("passed") is True for item in outcomes):
                    reasons.append(f"{name} assessment is incomplete or failed.")
        return {"ready": not reasons, "stage": "scoped-expansion" if not reasons else "foundation", "blockers": reasons,
                "manifest_hash": MANIFEST_HASH, "suite_hash": SUITE_HASH, "revision": self.revision(key),
                "assessment": report, "scope": "Finite measured benchmark; not proof of unrestricted mature understanding."}

    def enqueue(self, kind: str, payload: dict) -> str:
        encoded = json.dumps(payload, sort_keys=True, allow_nan=False)
        if len(encoded.encode()) > 1_000_000: raise ValueError("Queue entry exceeds 1 MB.")
        identity = payload
        if kind == "video": identity = {"source_page": payload.get("rights", {}).get("source_page"), "title": payload.get("title")}
        elif kind == "source-discovery": identity = {"source_page": payload.get("source_page")}
        identifier = digest({"kind": kind, "payload": identity})
        with self.connect() as db:
            db.execute("INSERT OR IGNORE INTO queue(id,created,kind,payload) VALUES (?,?,?,?)", (identifier, time.time(), kind, encoded))
            if kind == "video" and payload.get("rights", {}).get("review_status") == "source_verified":
                existing = db.execute("SELECT state,payload FROM queue WHERE id=?", (identifier,)).fetchone()
                saved = json.loads(existing["payload"])
                if existing["state"] == "queued" and saved.get("content_review", {}).get("review_status") != "verified":
                    db.execute("UPDATE queue SET payload=? WHERE id=?", (encoded, identifier))
        return identifier

    def exclude_nonreal(self) -> int:
        """Retain an audit trail while withdrawing earlier animated/fiction entries."""
        count = 0
        with self.connect() as db:
            for row in db.execute("SELECT id,payload FROM queue WHERE kind='video' AND state='queued'").fetchall():
                item = json.loads(row["payload"])
                if item.get("title") in {"Big Buck Bunny", "Tears of Steel"} or item.get("content_review", {}).get("capture_type") in {"animation", "synthetic", "fiction"}:
                    db.execute("UPDATE queue SET state='excluded',error=? WHERE id=?", ("User requires real footage only; no cartoons, synthetic footage, or staged fiction.", row["id"]))
                    count += 1
        return count

    def items(self, key: str, checkpoint: str = "", limit: int = 100, *, include_excluded: bool = False) -> list[dict]:
        gate = self.gate(key, checkpoint)
        with self.connect() as db:
            rows = db.execute("SELECT * FROM queue WHERE (? OR state != 'excluded') ORDER BY created,id LIMIT ?", (include_excluded, min(max(limit, 1), 200))).fetchall()
        result = []
        for row in rows:
            payload = json.loads(row["payload"])
            if payload.get("brain_key") not in (None, key): continue
            blockers = license_blockers(payload) if row["kind"] == "video" else []
            if row["kind"] == "source-discovery": blockers.append("Discovery reference only; each clip needs separate rights and real-footage review.")
            if not gate["ready"]: blockers.append("Foundation assessments must pass before broad experience training.")
            review = payload.get("reviewed_experience")
            if not isinstance(review, dict) or review.get("outcome_verified") is not True or not review.get("reviewer") or not review.get("observed_outcome"):
                blockers.append("Observed outcomes and all-prerogative associations need annotation.")
            else:
                checked = review.get("checked_prerogatives")
                if not isinstance(checked, list) or not all(isinstance(item, str) for item in checked) or len(checked) != len(IDS) or set(checked) != set(IDS) or review.get("conflicts") != []:
                    blockers.append("The reviewed experience must assess all twelve prerogatives with no unresolved conflict.")
            result.append({"id": row["id"], "kind": row["kind"], "state": row["state"], "payload": payload,
                           "eligible": not blockers and row["state"] == "queued", "blockers": blockers, "error": row["error"]})
        return result
